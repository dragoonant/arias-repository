// Rough 0-10 ratings used for the stat bars on the role picker.
export function roleStats(role) {
  const w = role.weapon;
  const dps = (w.damage * w.pellets) / w.fireDelay;
  return {
    Health: Math.round((role.hp / 170) * 10),
    Speed: Math.round((role.speed / 9.5) * 10),
    Damage: Math.min(10, Math.round(dps / 16)),
    Range: Math.min(10, Math.round(Math.log2(w.range / 20) * 2.3)),
  };
}
